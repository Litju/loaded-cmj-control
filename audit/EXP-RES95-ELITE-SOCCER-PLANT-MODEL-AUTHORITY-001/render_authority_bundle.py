def render_json(key, meta, decisions):
    payload = {
        "schema_version": "1.0.0",
        "artifact": meta["file"],
        "artifact_role": "res95_model_authority",
        "authority_id": AUTHORITY_ID,
        "mission": MISSION,
        "linear_issue": "RES-95",
        "sport_context_id": CONTEXT,
        "system_authority_id": INPUTS["system_authority_id"],
        "model_revision": INPUTS["model"]["MODEL_REVISION"],
        "model_id": INPUTS["model"]["MODEL_ID"],
        "status": "FROZEN_FOR_RES83_IMPLEMENTATION",
        "purpose": meta["purpose"],
        "machine_readable_inputs": "AUTHORITY_INPUTS.json",
        "derived_quantities": "DERIVED_QUANTITIES.json",
        "cross_references": meta["refs"],
        "classification_taxonomy": CLASSIFICATIONS,
        "decisions": decisions,
    }
    (HERE / f"{meta['file']}.json").write_text(json.dumps(payload, indent=2) + "\n")


def render_md(key, meta, decisions):
    lines = [f"# {meta['file']} — {meta['title']}", ""]
    lines += [
        f"**MISSION:** `{MISSION}`  ",
        f"**LINEAR:** `RES-95` (active unit; parent RES-83)  ",
        f"**AUTHORITY_ID:** `{AUTHORITY_ID}`  ",
        f"**SPORT_CONTEXT_ID:** `{CONTEXT}`  ",
        f"**MODEL:** `{INPUTS['model']['MODEL_REVISION']}` / `{INPUTS['model']['MODEL_ID']}`  ",
        "**STATUS:** FROZEN_FOR_RES83_IMPLEMENTATION  ",
        "**INPUTS:** `AUTHORITY_INPUTS.json` → `DERIVED_QUANTITIES.json` (deterministic; see `build_authority_numbers.py`)  ",
        "",
        f"## Purpose",
        "",
        meta["purpose"],
        "",
        "## Context",
        "",
    ]
    for p in meta["preamble"]:
        lines += [p, ""]
    lines += ["## Frozen decisions", "",
              "| ID | Decision | Value | Units | Classification | Sources |",
              "|---|---|---|---|---|---|"]
    for dec in decisions:
        val = dec["value"]
        if isinstance(val, (dict, list)):
            val = f"`{json.dumps(val, ensure_ascii=True)}`"
        else:
            val = str(val)
        if len(val) > 260:
            val = val[:257] + "..."
        stmt = dec["statement"].replace("|", "\\|")
        lines.append(f"| `{dec['id']}` | {stmt} | {val} | {dec['units']} | `{dec['classification']}` | {dec['sources']} |")
    lines += ["", "## Sensitivity and downstream obligations", ""]
    any_sens = False
    for dec in decisions:
        if dec["sensitivity"] not in ("—", ""):
            any_sens = True
            lines.append(f"- **{dec['id']}** — {dec['sensitivity']}")
    if not any_sens:
        lines.append("None beyond the generic V&V obligations.")
    notes = [d for d in decisions if d["notes"]]
    lines += ["", "## Notes and locators", ""]
    for dec in notes:
        lines.append(f"- **{dec['id']}** — {dec['notes']} (locator: {dec['locator']}; sources: {dec['sources']}).")
    lines += ["", "## Cross-references", ""]
    for r in meta["refs"]:
        lines.append(f"- `{r}`")
    lines += ["", "---", "",
              "This artifact is part of the RES-95 model authority bundle. It freezes specification only: it implements no Plant, controller or scorer code.", ""]
    (HERE / f"{meta['file']}.md").write_text("\n".join(lines))


def render_evidence_table():
    header = ["ROW_TYPE", "ROW_ID", "ARTIFACT", "DECISION_OR_CITATION", "VALUE", "UNITS", "CLASSIFICATION",
              "SOURCE_IDS", "LOCATOR", "SENSITIVITY_REQUIRED", "VERIFICATION_STATUS", "NOTES"]
    rows = []
    for s in SOURCES:
        rows.append(["SOURCE", s["id"], "SOURCE_REGISTRY", s["citation"], s["doi"], "—", "SOURCE",
                     "—", s["scope"], "—", s["verification"], s["notes"]])
    counts = {}
    for key, decs in DECISIONS.items():
        fname = ARTIFACTS[key]["file"]
        for dec in decs:
            val = dec["value"]
            if isinstance(val, (dict, list)):
                val = json.dumps(val, ensure_ascii=True)
            rows.append(["DECISION", dec["id"], fname, dec["statement"], str(val), dec["units"],
                         dec["classification"], dec["sources"], dec["locator"],
                         dec["sensitivity"], "RECOMPUTED_FROM_INPUTS", dec["notes"]])
            counts[dec["classification"]] = counts.get(dec["classification"], 0) + 1
    with (HERE / "MODEL_AUTHORITY_EVIDENCE_TABLE.csv").open("w", newline="") as fh:
        w = csv.writer(fh)
        w.writerow(header)
        w.writerows(rows)
    # markdown version
    lines = ["# MODEL_AUTHORITY_EVIDENCE_TABLE", "",
             f"Evidence table for `{AUTHORITY_ID}`. "
             f"{len(SOURCES)} sources and {sum(counts.values())} classified decisions.", "",
             "## Decision classification counts", ""]
    for c in CLASSIFICATIONS:
        lines.append(f"- `{c}`: {counts.get(c, 0)}")
    lines += ["", "## Sources", "", "| ID | Citation | DOI/Standard | Verification | Notes |", "|---|---|---|---|---|"]
    for s in SOURCES:
        cit = s["citation"]
        if len(cit) > 220:
            cit = cit[:217] + "..."
        lines.append(f"| `{s['id']}` | {cit.replace('|', '/')} | {s['doi']} | `{s['verification']}` | {s['notes'][:150].replace('|', '/')} |")
    lines += ["", "## Decisions", "", "| ID | Artifact | Decision | Value | Class | Sources | Sensitivity |", "|---|---|---|---|---|---|---|"]
    for key, decs in DECISIONS.items():
        fname = ARTIFACTS[key]["file"]
        for dec in decs:
            val = dec["value"]
            if isinstance(val, (dict, list)):
                val = json.dumps(val, ensure_ascii=True)
            val = str(val)
            if len(val) > 160:
                val = val[:157] + "..."
            lines.append(f"| `{dec['id']}` | `{fname}` | {dec['statement'].replace('|', '/')[:170]} | {val.replace('|', '/')} | `{dec['classification']}` | {dec['sources']} | {dec['sensitivity'].replace('|', '/')[:120]} |")
    lines += ["", "Full machine-readable table: `MODEL_AUTHORITY_EVIDENCE_TABLE.csv`.", ""]
    (HERE / "MODEL_AUTHORITY_EVIDENCE_TABLE.md").write_text("\n".join(lines))
    return counts


def main():
    assert set(DECISIONS) == set(ARTIFACTS), (set(DECISIONS) ^ set(ARTIFACTS))
    for key, meta in ARTIFACTS.items():
        decs = DECISIONS[key]
        for dec in decs:
            assert dec["classification"] in CLASSIFICATIONS, (dec["id"], dec["classification"])
        render_json(key, meta, decs)
        render_md(key, meta, decs)
    counts = render_evidence_table()
    print("rendered artifacts:", len(ARTIFACTS), "decision count:", sum(counts.values()))
    print(json.dumps(counts, indent=1))


if __name__ == "__main__":
    main()
