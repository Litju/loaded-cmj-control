def d(path: str):
    node = DER
    for part in path.split("."):
        node = node[part]
    return node


def n(v, sig=9):
    if isinstance(v, bool):
        return str(v)
    if isinstance(v, (int, float)):
        if v == 0:
            return "0"
        return f"{v:.{sig}g}"
    if isinstance(v, list):
        return "[" + ", ".join(n(x, sig) for x in v) + "]"
    return str(v)


def D(id, statement, value, units, classification, sources, locator, sensitivity="—", notes=""):
    return dict(id=id, statement=statement, value=value, units=units, classification=classification,
                sources=sources, locator=locator, sensitivity=sensitivity, notes=notes)


